/**
 * Definition for a binary tree node.
 * public class TreeNode {
 *     int val;
 *     TreeNode left;
 *     TreeNode right;
 *     TreeNode() {}
 *     TreeNode(int val) { this.val = val; }
 *     TreeNode(int val, TreeNode left, TreeNode right) {
 *         this.val = val;
 *         this.left = left;
 *         this.right = right;
 *     }
 * }
 */
class Solution {
    public boolean isUnivalTree(TreeNode root) {
        return f(root,root.val);
    }
    boolean f(TreeNode root,int d){
        if(root==null){
            return true;
        }
        if(root.val!=d){
            return false;
        }
        return f(root.left,d)&&f(root.right,d);
    }
}

