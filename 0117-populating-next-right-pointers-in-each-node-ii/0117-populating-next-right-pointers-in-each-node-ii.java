class Solution {
    public Node connect(Node root) {
        if(root==null){
            return null;
        }
        Queue<Node> q=new LinkedList<>();
        q.add(root);
        while(!q.isEmpty()){
            int n=q.size();
            Node h=null;
            Node t=null;
            for(int i=0;i<n;i++){
                Node x=q.remove();
                if(i==0){
                    h=x;
                    t=h;
                }
                else{
                    t.next=x;
                    t=t.next;
                }
                if(x.left!=null){
                    q.add(x.left);
                }
                if(x.right!=null){
                    q.add(x.right);
                }
            }
        }
        return root;
    }
}

