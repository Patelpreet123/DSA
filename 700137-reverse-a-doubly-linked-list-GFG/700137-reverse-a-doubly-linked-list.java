class Solution {
    public Node reverse(Node head) {
        // code here
        Node c=head;
        Node l=null;
        while(c!=null){
            l=c.prev;
            c.prev=c.next;
            c.next=l;
            c=c.prev;
        }
        return l.prev;
    }
}

