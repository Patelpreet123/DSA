/**
 * Definition for a binary tree node.
 * public class TreeNode {
 *     int val;
 *     TreeNode left;
 *     TreeNode right;
 *     TreeNode() {}
 *     TreeNode(int val) { this.val = val; }
 *     TreeNode(int val, TreeNode left, TreeNode right) {
 *         this.val = val;
 *         this.left = left;
 *         this.right = right;
 *     }
 * }
 */
class Solution {
    public TreeNode bstToGst(TreeNode root) {
        int[] s={0};
        f(root,s);
        return root;
    }
    void f(TreeNode root,int[] s){
        if(root==null){
            return;
        }
        f(root.right,s);
        s[0]+=root.val;
        root.val=s[0];
        f(root.left,s);
    }
}

